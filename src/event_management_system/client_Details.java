    private void btnUpdateClientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateClientActionPerformed
        try {
            String nic = txtIdNo.getText().trim();
            String name = txtName.getText().trim();
            String phone = txtPhone.getText().trim();
            String email = txtEmail.getText().trim();
            String address = txtAddress.getText().trim();

            if (selectedClientID.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please select a client from the table to update!");
                return;
            }

            if (name.isEmpty() || phone.isEmpty() || nic.isEmpty() || address.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill all the required fields!", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            

            // Database Update 
            String sql = "UPDATE clients SET client_name=?, nic=?, contact_number=?, email=?, address=? WHERE client_id=?";
            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, name);
            pst.setString(2, nic);
            pst.setString(3, phone);
            pst.setString(4, email);
            pst.setString(5, address);
            pst.setString(6, selectedClientID);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Client Updated Successfully!");

            // Table
            loadClientTable();

            // Cancel Button Code Click 
            btnCancelClient.doClick();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateClientActionPerformed

