    private void btnAddClientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddClientActionPerformed
        try {

            String nic = txtIdNo.getText();
            String name = txtName.getText();
            String phone = txtPhone.getText();
            String email = txtEmail.getText();
            String address = txtAddress.getText();

            if (name.isEmpty() || phone.isEmpty() || nic.isEmpty() || address.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill the required fields!");
                return;
            }

            

            String checkSql = "SELECT * FROM clients WHERE nic = ?";
            PreparedStatement checkPst = conn.prepareStatement(checkSql);
            checkPst.setString(1, nic);
            ResultSet checkRs = checkPst.executeQuery();

            if (checkRs.next()) {

                JOptionPane.showMessageDialog(this, "This ID Card No (NIC) already exists in the system!", "Duplicate Record", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String newClientID = "C-1001";
            Statement s = conn.createStatement();
            ResultSet rs = s.executeQuery("SELECT MAX(client_id) FROM clients");

            if (rs.next() && rs.getString(1) != null) {
                String maxId = rs.getString(1); // C-1005
                long idNum = Long.parseLong(maxId.substring(2)); // C- 1005 
                idNum++; // (1006)
                newClientID = "C-" + String.format("%04d", idNum); //  C-1006
            }

            String sql = "INSERT INTO clients (client_id, client_name, nic, contact_number, email, address) VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, newClientID);
            pst.setString(2, name);
            pst.setString(3, nic);
            pst.setString(4, phone);
            pst.setString(5, email);
            pst.setString(6, address);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Client Added Successfully!\nNew Client ID: " + newClientID);

            txtIdNo.setText("");
            txtName.setText("");
            txtPhone.setText("");
            txtEmail.setText("");
            txtAddress.setText("");

            loadClientTable();

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }


    }//GEN-LAST:event_btnAddClientActionPerformed

