    private void loadClientTable() {
        try {
            

            Statement s = conn.createStatement();

            ResultSet rs = s.executeQuery("SELECT * FROM clients");

            DefaultTableModel model = (DefaultTableModel) jTableClients.getModel();
            model.setRowCount(0);

            while (rs.next()) {

                String id = rs.getString("client_id");
                String name = rs.getString("client_name");
                String nic = rs.getString("nic");
                String phone = rs.getString("contact_number");
                String email = rs.getString("email");
                String address = rs.getString("address");

                model.addRow(new Object[]{id, name, nic, phone, email, address});
            }
        } catch (SQLException ex) {
            System.getLogger(client_Details.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }

    }
